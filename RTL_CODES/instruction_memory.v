`timescale 1ns/1ps

module instruction_memory(

    input [7:0] addr,
    output reg [31:0] instruction

);

always @(*) begin

case(addr)

//////////////////////////////////////////////////////////////
// Register Initialization
//////////////////////////////////////////////////////////////

8'd0  : instruction = 32'h2001000A; // addi r1,r0,10
8'd1  : instruction = 32'h20020014; // addi r2,r0,20
8'd2  : instruction = 32'h20030055; // addi r3,r0,55
8'd3  : instruction = 32'h200400AA; // addi r4,r0,AA

//////////////////////////////////////////////////////////////
// R-Type Operations
//////////////////////////////////////////////////////////////

8'd4  : instruction = 32'h00222820; // add r5,r1,r2
8'd5  : instruction = 32'h00413022; // sub r6,r2,r1
8'd6  : instruction = 32'h00643824; // and r7,r3,r4
8'd7  : instruction = 32'h00644025; // or  r8,r3,r4
8'd8  : instruction = 32'h00644826; // xor r9,r3,r4

//////////////////////////////////////////////////////////////
// RAM Writes
//////////////////////////////////////////////////////////////

8'd9  : instruction = 32'hAC050000; // sw r5,0(r0)
8'd10 : instruction = 32'hAC060004; // sw r6,4(r0)
8'd11 : instruction = 32'hAC070008; // sw r7,8(r0)
8'd12 : instruction = 32'hAC08000C; // sw r8,12(r0)
8'd13 : instruction = 32'hAC090010; // sw r9,16(r0)

//////////////////////////////////////////////////////////////
// RAM Reads
//////////////////////////////////////////////////////////////

8'd14 : instruction = 32'h8C0A0000; // lw r10,0(r0)
8'd15 : instruction = 32'h8C0B0004; // lw r11,4(r0)
8'd16 : instruction = 32'h8C0C0008; // lw r12,8(r0)
8'd17 : instruction = 32'h8C0D000C; // lw r13,12(r0)
8'd18 : instruction = 32'h8C0E0010; // lw r14,16(r0)

//////////////////////////////////////////////////////////////
// Branch NOT Taken
//////////////////////////////////////////////////////////////

8'd19 : instruction = 32'h114B0001; // beq r10,r11,+1

//////////////////////////////////////////////////////////////
// ADD
//////////////////////////////////////////////////////////////

8'd20 : instruction = 32'h014B7820; // add r15,r10,r11

//////////////////////////////////////////////////////////////
// Branch Taken
//////////////////////////////////////////////////////////////

8'd21 : instruction = 32'h114A0001; // beq r10,r10,+1

//////////////////////////////////////////////////////////////
// Skipped if branch taken
//////////////////////////////////////////////////////////////

8'd22 : instruction = 32'h200F00FF;

//////////////////////////////////////////////////////////////
// Ethernet Test
//////////////////////////////////////////////////////////////

8'd23 : instruction = 32'h20011000; // Ethernet base

8'd24 : instruction = 32'h20020055; // data

8'd25 : instruction = 32'hAC220000; // TX DATA

8'd26 : instruction = 32'h20030001; // start

8'd27 : instruction = 32'hAC230004; // TX START

8'd28 : instruction = 32'h8C240004; // STATUS

8'd29 : instruction = 32'h8C250000; // RX DATA

//////////////////////////////////////////////////////////////
// More Memory Activity
//////////////////////////////////////////////////////////////

8'd30 : instruction = 32'hAC050020;
8'd31 : instruction = 32'hAC060024;
8'd32 : instruction = 32'hAC070028;

8'd33 : instruction = 32'h8C160020;
8'd34 : instruction = 32'h8C170024;
8'd35 : instruction = 32'h8C180028;

//////////////////////////////////////////////////////////////
// Repeat Ethernet
//////////////////////////////////////////////////////////////

8'd36 : instruction = 32'hAC220000;
8'd37 : instruction = 32'hAC230004;

//////////////////////////////////////////////////////////////
// Infinite Loop
//////////////////////////////////////////////////////////////

8'd38 : instruction = 32'h08000026;

default:
instruction = 32'h00000000;

endcase

end

endmodule